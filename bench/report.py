"""Builds docs/REPORT.md, the Steps 1 to 4 report, from the committed result files only. No number is typed by hand.
Intervals: Wilson 95% for shares; bootstrap over clusters (2,000 resamples, seed 0) for totals, ratios and gains.
Usage: python bench/report.py"""
import json, os
from pathlib import Path
import numpy as np

R = Path(__file__).resolve().parent.parent / "results"
CASES = ["case30", "case118", "case_ACTIVSg200", "case300", "case_ACTIVSg500", "case_ACTIVSg2000"]
NAME = dict(case30="IEEE 30", case118="IEEE 118", case_ACTIVSg200="Illinois 200 (synthetic)", case300="IEEE 300",
            case_ACTIVSg500="South Carolina 500 (synthetic)", case_ACTIVSg2000="Texas 2,000 (synthetic)")
SEAS = dict(summer_peak="summer peak", winter_peak="winter peak", light_load="light load")
rng = np.random.default_rng(0)
J = lambda f: json.load(open(R / f))
md = []
W = md.append


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"),) * 2
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def pct(k, n):
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]" if n else "n/a"


def boot(f, *arrs, B=2000):
    n = len(arrs[0]); vals = []
    for _ in range(B):
        i = rng.integers(0, n, n); vals.append(f(*[a[i] for a in arrs]))
    return np.percentile(vals, [2.5, 97.5])


def table(head, rows):
    W("| " + " | ".join(head) + " |"); W("|" + "---|" * len(head))
    for r in rows:
        W("| " + " | ".join(str(x) for x in r) + " |")
    W("")


W("# Certified Interconnection: Steps 1 to 4, results report")
W("")
W("Generated by `bench/report.py` from the files in `results/`. Definitions, hypotheses and what would count as failure "
  "are in `docs/FORMULATION.md`. 95% intervals in brackets: Wilson for shares, bootstrap over clusters for totals.")
W("")

# ------------------------------------------------------------------ Step 1
W("## Step 1. The physics engine")
W("")
W("### 1a. Agreement with an independent solver (H1)")
W("grid-engine (Power Grid Model, batch) against PYPOWER (a port of MATPOWER's Newton-Raphson), every season and every "
  "contingency set, voltage magnitude difference (`bench/validate_pypower.py`).")
W("")
rows = []; tot_n = tot_c = 0
for c in CASES:
    for tag, f in (("off", f"validate_pypower_{c}.json"), ("on", f"validate_pypower_{c}_qlim.json")):
        if not (R / f).exists():
            continue
        d = J(f); n = cmp = dis = 0; worst = 0.0; dv99 = []
        for s, v in d["seasons"].items():
            for k, x in v.items():
                n += x["n"]; cmp += x["compared"]; dis += x["converged_pgm_only"] + x["converged_pypower_only"]
                if x["max_dv"]:
                    worst = max(worst, x["max_dv"]["1.0"]); dv99.append(x["max_dv"]["0.99"])
        if tag == "off":
            tot_n += n; tot_c += cmp
        rows.append([NAME[c], tag, n, cmp, dis, f"{max(dv99):.1e}", f"{worst:.1e}"])
table(["grid", "reactive limits", "cases", "both converged", "convergence disagreements", "worst 99th pct |dV| (pu)", "worst |dV| (pu)"], rows)
W(f"Without reactive limits: {tot_c:,} of {tot_n:,} cases converged in both solvers and agree; the rest diverged in both. "
  "With reactive limits, the reference is MATPOWER's PV-to-PQ outer loop (`gridengine/qlim_ref.py`); the few larger "
  "differences are single cases where a generator sits at its limit and the two loops switch a different generator.")
W("")
ref = J("validate_reference.json")
W(f"IEEE 300 base case against Power Grid Model's own validated solution: |dV| {ref['case300']['pgm_reference_max_dv']:.1e} pu "
  f"over {ref['case300']['pgm_reference_matched']} buses. (pandapower's MATPOWER converter disagrees with both on IEEE 300 and "
  "Texas 2,000, so it is used only where it agrees: see `results/validate_<case>.json` part A.)")
W("")

W("### 1b. The linear (DC) baseline (H2)")
W("Cases a DC security check calls secure while full AC is not (thermal, voltage or divergence), per season and set "
  "(`bench/validate.py`). Reactive limits off.")
W("")
rows = []
for c in CASES:
    d = J(f"validate_{c}.json")
    for s, v in d["B_dc_vs_ac"].items():
        for k, x in v.items():
            bad = x["dc_secure_ac_insecure"]; ac_bad = x["n"] - x["ac_secure"]
            r = x["dc_secure_ac_insecure_by_reason"]
            rows.append([NAME[c], SEAS[s], k, x["n"], ac_bad, bad, pct(bad, ac_bad) if ac_bad else "no AC-insecure cases",
                         f"{r['thermal']}/{r['voltage_only']}/{r['diverged']}"])
table(["grid", "season", "set", "cases", "AC insecure", "DC says secure", "share of AC-insecure cases DC misses", "thermal/voltage/diverged"], rows)

W("### 1c. Speed")
rows = []
for c in ["case118", "case300", "case_ACTIVSg2000"]:
    if (R / f"bench_{c}.json").exists():
        b = J(f"bench_{c}.json")
        rows.append([NAME[c], f"{b['seasons']['summer_peak']['P1']['ms_per_case']:.1f}", f"{b['pandapower_loop']['ms_per_case']:.0f}"])
table(["grid", "Power Grid Model batch, ms per outage", "pandapower loop (no numba), ms per outage"], rows)

# ------------------------------------------------------------------ Step 2
W("## Step 2. Individual and cluster capacity")
W("")
for tag, f in (("reactive limits off", "capacity_case118.json"), ("reactive limits on", "capacity_case118_qlim.json")):
    if not (R / f).exists():
        continue
    C = J(f)
    W(f"### 2a. Every bus, IEEE 118, {tag} (H3)")
    W(f"Largest new generation or load each bus can take (cap {C['map_cap_mw']:.0f} MW), with no outages (N-0) and under "
      "every single outage (P1).")
    W("")
    rows = []
    for kind in ("gen", "load"):
        for s in SEAS:
            m = [x for x in C["map"] if x["kind"] == kind and x["season"] == s]
            n0 = np.array([x["N0"]["mw"] for x in m]); p1 = np.array([x["P1"]["mw"] for x in m])
            ok = n0 > 1e-6; loss = 1 - p1[ok] / n0[ok]
            lo, hi = boot(np.median, loss)
            rows.append([kind, SEAS[s], f"{np.median(n0):.0f}", f"{np.median(p1):.0f}", f"{100 * np.median(loss):.0f}% [{100 * lo:.0f}, {100 * hi:.0f}]"])
    table(["new", "season", "median N-0 MW", "median P1 MW", "median share lost to outages"], rows)
    W(f"### 2b. Clusters, IEEE 118, {tag} (H4)")
    W(f"{len(C['clusters'])} clusters of 5 to 8 nearby requests (about 30% large loads), 30 per season.")
    W("")
    rows = []
    for cond in ("P1", "P1+P7"):
        r = [x[cond] for x in C["clusters"]]
        best = np.array([x["cluster"]["mw"] for x in r]); first = np.array([x["queue"]["mw"] for x in r])
        lf = np.array([x["largest_first"]["mw"] for x in r]); fa = np.array([x["fits_alone_mw"] for x in r])
        g = best.sum() / first.sum() - 1; lo, hi = boot(lambda a, b: a.sum() / b.sum() - 1, best, first)
        k = int((best > first + 1e-6).sum()); over = int((fa > best + 1e-6).sum())
        rows.append([cond, f"{first.sum():,.0f}", f"{lf.sum():,.0f}", f"{best.sum():,.0f}",
                     f"+{100 * g:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]", pct(k, len(r)), pct(over, len(r))])
    table(["contingencies", "first come MW", "largest first MW", "best subset MW", "best vs first come",
           "clusters where best beats first come", "clusters where 'fits alone' overpromises"], rows)

if (R / "baselines_case118.json").exists():
    B = J("baselines_case118.json")
    W("### 2c. The linear (DC) decisions, IEEE 118 (H5)")
    rows = []
    for cond in ("P1", "P1+P7"):
        r = [x[cond] for x in B["clusters"]]
        k = sum(not x["dc_pick_ac_secure"] for x in r)
        dc = np.array([v for x in r for v in x["dc_individual"]]); ac = np.array([v for x in r for v in x["ac_individual"]])
        rows.append([cond, pct(k, len(r)), pct(int((dc > ac + 1).sum()), len(dc)), pct(int((dc < ac - 1).sum()), len(dc))])
    table(["contingencies", "DC cluster pick that is AC-insecure", "DC overstates a request's capacity (>1 MW)",
           "DC understates it (>1 MW)"], rows)

# ------------------------------------------------------------------ Step 3
if (R / "options_case118.json").exists():
    O = J("options_case118.json"); S = O["summary"]
    W("## Step 3. Ways to make room (IEEE 118, P1)")
    W(f"For the {S['n_not_fit']} of {S['n_clusters']} clusters that don't fully fit: extra MW each option admits beyond the "
      "best plain subset. Every admitted set is re-checked in AC under its own rule "
      f"(all re-checks passed: {S['all_rechecks_pass']}).")
    W("")
    label = dict(flex_load_50="flexible load, keeps 50% after an outage", flex_load_0="flexible load, drops to 0 after an outage",
                 storage_25="battery at each load, 25% of the load", storage_50="battery at each load, 50% (same rule as flexible 50%)",
                 ras_gen_0="generation tripped after an outage (remedial action scheme)", switch="one line opened permanently",
                 partial="connect the left-out requests at partial size")
    plain = np.array([x["plain"]["mw"] for x in O["clusters"]])
    rows = []
    for key, v in S["options"].items():
        mw = np.array([x["options"][key]["mw"] for x in O["clusters"]])
        lo, hi = boot(lambda a, b: a.sum() - b.sum(), mw, plain)
        rows.append([label.get(key, key), f"{v['total_mw']:,.0f}", f"+{v['gain_mw']:,.0f} [{lo:,.0f}, {hi:,.0f}]",
                     pct(v["clusters_with_gain"], S["n_clusters"])])
    W(f"Plain best subset: {S['plain_mw']:,.0f} MW of {S['requested_mw']:,.0f} MW requested.")
    W("")
    table(["option", "total MW", "gain MW", "clusters where it adds MW"], rows)

# ------------------------------------------------------------------ Step 4
if (R / "timelines_pjm.json").exists():
    T = J("timelines_pjm.json")
    W("## Step 4. Time and cost")
    W("### 4a. How long PJM requests take (PJM's public queue)")
    rows = [["entry to commercial operation, all", T["service"]["overall"]["n"], T["service"]["overall"]["median"],
             f"{T['service']['overall']['p25']} to {T['service']['overall']['p75']}"]]
    for f, v in sorted(T["service"]["by_fuel"].items(), key=lambda kv: -kv[1]["n"]):
        if not v.get("small_sample"):
            rows.append([f"  {f}", v["n"], v["median"], f"{v['p25']} to {v['p75']}"])
    if "withdrawal" in T and "overall" in T["withdrawal"]:
        w = T["withdrawal"]["overall"]; rows.append(["entry to withdrawal", w["n"], w["median"], f"{w['p25']} to {w['p75']}"])
    table(["path", "requests", "median years", "25th to 75th pct"], rows)
if (R / "costs_case118.json").exists():
    K = J("costs_case118.json")
    W("### 4b. What it would take to admit the rest (illustrative, IEEE 118)")
    W(K.get("caveat", ""))
    W("")
    cls = {}
    for r in K["rows"]:
        if r.get("set") != "P1":
            continue
        u = (r.get("best_subset_plus_rest") or {}).get("upgrade")
        if u:
            cls[u["upgrade_class"]] = cls.get(u["upgrade_class"], 0) + 1
    table(["first upgrade needed (binding element once the rest is added), single outages", "clusters"], sorted(cls.items(), key=lambda kv: -kv[1]))
    W("Cost and time ranges for each class, with sources, are in `data/costs/sources.csv` and `RESULTS_COSTS.md`.")
    W("")

W("## Limits")
W("Synthetic and test grids only; our contingency definitions; all-or-nothing admission unless stated; one grid for "
  "Steps 2 to 4; costs are illustrative on a test grid. See `docs/FORMULATION.md`.")
os.makedirs(R.parent / "docs", exist_ok=True)
(R.parent / "docs" / "REPORT.md").write_text("\n".join(md), encoding="utf-8")
print("wrote docs/REPORT.md", len(md), "lines")
