import pandapower.networks as pn
for name in ["case30", "case118"]:
    net = getattr(pn, name)()
    print("=====", name)
    print("bus in_service all:", net.bus.in_service.all())
    print("load const_z pct:", net.load.const_z_p_percent.unique(), "const_i:", net.load.const_i_p_percent.unique())
    print("load scaling:", net.load.scaling.unique(), "in_service:", net.load.in_service.unique())
    print("shunt q:", net.shunt[["bus", "q_mvar", "p_mw", "vn_kv", "step"]].to_string())
    print("gen at slack bus:", int(net.ext_grid.bus.iloc[0]), "gens on that bus:", net.gen.index[net.gen.bus == net.ext_grid.bus.iloc[0]].tolist())
    print("gen slack flag:", net.gen.slack.unique(), "gen in_service:", net.gen.in_service.unique(), "scaling:", net.gen.scaling.unique())
    print("ext_grid:", net.ext_grid[["bus", "vm_pu", "va_degree"]].to_string())
    print("trafo taps:")
    print(net.trafo[["hv_bus", "lv_bus", "sn_mva", "vn_hv_kv", "vn_lv_kv", "vk_percent", "vkr_percent", "pfe_kw", "i0_percent", "shift_degree", "tap_side", "tap_neutral", "tap_pos", "tap_step_percent", "tap_step_degree", "in_service"]].head(15).to_string())
    print("trafo tap_pos unique:", net.trafo.tap_pos.unique(), "tap_side:", net.trafo.tap_side.unique())
    print("line parallel:", net.line.parallel.unique(), "df:", net.line.df.unique(), "line in_service:", net.line.in_service.unique())
    print("line max_i_ka nan:", net.line.max_i_ka.isna().sum())
    print("line c_nf range:", net.line.c_nf_per_km.min(), net.line.c_nf_per_km.max())
    print("line g_us range:", net.line.g_us_per_km.min(), net.line.g_us_per_km.max())
    print("gen min/max q nan:", net.gen.min_q_mvar.isna().sum(), net.gen.max_q_mvar.isna().sum())
